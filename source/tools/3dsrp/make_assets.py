#!/usr/bin/env python3
"""Rasterize licensed DejaVu glyphs and a geometric 3DSRP launcher icon."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[2]
fonts=[]
for size in (8,10,11,14,18,22,32):
    name='DejaVuSans.ttf' if size<=11 else 'DejaVuSans-Bold.ttf'
    f=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/'+name,size)
    pixels=bytearray();glyphs=[]
    for c in map(chr,range(32,127)):
        x0,y0,x1,y1=f.getbbox(c)
        w,h=x1-x0,y1-y0
        im=Image.new('L',(max(w,1),max(h,1)));ImageDraw.Draw(im).text((-x0,-y0),c,font=f,fill=255)
        glyphs.append((len(pixels),w,h,x0,y0,round(f.getlength(c))))
        if w and h:pixels.extend(im.tobytes())
    fonts.append((size,pixels,glyphs))
lines=['/* Generated by tools/3dsrp/make_assets.py; see docs/THREEDSRP-FONT-LICENSE.txt. */','#ifndef THREEDSRP_UI_FONTS_H','#define THREEDSRP_UI_FONTS_H']
for size,pixels,glyphs in fonts:
    lines += [f'static const unsigned char font_{size}_pixels[]={{']
    lines += [','.join(map(str,pixels[i:i+32]))+',' for i in range(0,len(pixels),32)]
    lines += ['};',f'static const UiGlyph font_{size}_glyphs[]={{']
    lines += ['{'+','.join(map(str,g))+'},' for g in glyphs]
    lines += ['};']
lines += ['static const UiFont fonts[]={']
for size,_,_ in fonts:lines += [f'{{{size},font_{size}_pixels,font_{size}_glyphs}},']
lines+=['};','#endif']
(ROOT/'3ds/app/include/ui_fonts.h').write_text('\n'.join(lines)+'\n')
# Original arched portal mark in the existing navy, blue and white palette.
s=4
im=Image.new('RGB',(48*s,48*s),(9,15,32));d=ImageDraw.Draw(im)
d.rounded_rectangle((s,s,47*s,47*s),radius=10*s,fill=(12,24,48))
def doorway(cx,top,half,bottom,color):
    d.pieslice(((cx-half)*s,top*s,(cx+half)*s,(top+2*half)*s),180,360,fill=color)
    d.rectangle(((cx-half)*s,(top+half)*s,(cx+half)*s,bottom*s),fill=color)
doorway(24,7,16,41,(59,135,255))
doorway(24,10,13,38,(9,15,32))
doorway(24,14,9,36,(122,179,255))
doorway(24,16,7,35,(12,24,48))
doorway(24,20,4,34,(230,240,255))
doorway(24,22,2,33,(9,15,32))
im.resize((48,48),Image.Resampling.LANCZOS).save(ROOT/'3ds/app/resources/3dsrp-icon.png')
print('Generated 3DSRP fonts and portal icon')
